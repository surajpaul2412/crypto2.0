    </div>
    <div class="abt-story" data-reveal>
      <div class="abt-story__prose">
        <p><span class="leadword">It began in 2010</span> with a stubborn idea and almost nothing else: that the instruments of India deserved to be deeply sampled — captured with their culture and history intact. We had no studio, no resources, and just a name: Crypto Cipher. So we started slowly, building the dream one step at a time — saving for the first microphones, finding the players, and raising a studio from scratch, tuned specifically for these instruments and the people who play them.</p>
        <p>We record talented musicians from across the country — players of instruments that are rare, regional, and often impossible to track down outside India. The libraries go deep: the breath of a harmonium's bellows, the click of its keys, percussion patterns played the way the tradition intends. That depth is why the work travels — from bedroom producers to composers scoring for Hollywood.</p>
        <p>The mission was never only software. It's local jobs, performances recorded at historical locations, and Indian classical music carried to a global audience ready to discover it.</p>
