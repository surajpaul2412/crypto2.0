<script>
(function(){
  var btn = document.getElementById('page-scroll');
  if(!btn) return;
  var textEl = btn.querySelector('.page-scroll__text');
  var labelText = { scroll: 'Scroll', top: 'Top' };

  var THRESHOLD = window.innerHeight * 0.8;   // morph after 80vh scroll
  var FOOTER_HIDE_OFFSET = 200;               // hide near footer

  var ticking = false;
  function update(){
    var y = window.scrollY || window.pageYOffset;
    var docH = document.documentElement.scrollHeight;
    var winH = window.innerHeight;

    // State morph
    if(y > THRESHOLD){
      if(!btn.classList.contains('is-top')){
        btn.classList.add('is-top');
        btn.setAttribute('aria-label', 'Back to top');
        if(textEl) textEl.textContent = labelText.top;
      }
    } else {
      if(btn.classList.contains('is-top')){
        btn.classList.remove('is-top');
        btn.setAttribute('aria-label', 'Scroll down');
        if(textEl) textEl.textContent = labelText.scroll;
      }
    }

    // Hide near footer
    var nearFooter = (y + winH) >= (docH - FOOTER_HIDE_OFFSET);
    btn.classList.toggle('is-hidden', nearFooter);

    ticking = false;
  }

  window.addEventListener('scroll', function(){
    if(ticking) return;
    ticking = true;
    requestAnimationFrame(update);
  }, { passive: true });

  window.addEventListener('resize', function(){
    THRESHOLD = window.innerHeight * 0.8;
  }, { passive: true });

  // Click handler — scroll down OR back to top
  btn.addEventListener('click', function(){
    if(btn.classList.contains('is-top')){
      /* MOTION v2: Lenis is the only scroll writer when present */
      if (window.__lenis && window.__lenis.scrollTo) { window.__lenis.scrollTo(0); }
      else { window.scrollTo({ top: 0, behavior: 'smooth' }); }
    } else {
      // Scroll down one viewport (Lenis writes when present)
      var target = window.scrollY + window.innerHeight * 0.9;
      if (window.__lenis && window.__lenis.scrollTo) { window.__lenis.scrollTo(target); }
      else { window.scrollBy({ top: window.innerHeight * 0.9, behavior: 'smooth' }); }
    }
  });

  // Initial
  update();
})();
</script>
